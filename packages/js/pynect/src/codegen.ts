import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { generate, type AsyncAPIDocument } from '@chanx-js/codegen';
import { resolveProject, type PynectProject, type ProjectOptions } from './config.js';
import { spawnWorker, waitForChild } from './python-runtime.js';
import { emitStreamSupport } from './codegen-stream.js';

/** Export AsyncAPI from Python, then generate the normal Chanx TypeScript client. */
export async function generateProject(
  input: ProjectOptions = {},
) {
  const project = resolveProject(input);
  await mkdir(project.outDir, { recursive: true });
  await exportSchema(project);
  const document = JSON.parse(await readFile(project.schemaPath, 'utf8')) as AsyncAPIDocument;
  const result = await generate(document, {
    outDir: project.outDir,
    validation: project.validation,
    emit: 'ts',
    format: project.format,
  });
  if (project.validation === 'zod') await deriveSchemaTypes(project.outDir);
  await emitStreamSupport(document, project.outDir);
  return Object.freeze({
    ...result,
    outDir: project.outDir,
    schemaPath: project.schemaPath,
  });
}

export type PynectGenerateResult = Awaited<ReturnType<typeof generateProject>>;

/** Replace duplicated generated declarations with types derived from Zod validators. */
export async function deriveSchemaTypes(outDir: string): Promise<void> {
  const schemasPath = path.join(outDir, 'schemas.ts');
  const validatorsPath = path.join(outDir, 'schemas.zod.ts');
  const [schemas, validators] = await Promise.all([
    readFile(schemasPath, 'utf8'),
    readFile(validatorsPath, 'utf8'),
  ]);
  const names = [...schemas.matchAll(/^export (?:interface|type) ([A-Za-z_$][\w$]*)\b/gmu)]
    .map(match => match[1]!);
  if (names.length === 0) throw new Error('Chanx generated no schema types.');
  const validatorNames = new Set(
    [...validators.matchAll(/^export const ([A-Za-z_$][\w$]*)Schema\b/gmu)]
      .map(match => match[1]!),
  );
  const missing = names.filter(name => !validatorNames.has(name));
  if (missing.length > 0) {
    throw new Error(`Generated Zod validators are missing schema types: ${missing.join(', ')}.`);
  }
  const imports = names.map(name => `  ${name}Schema,`);
  const aliases = names.map(name =>
    `export type ${name} = z.output<typeof ${name}Schema>;`
  );
  await writeFile(schemasPath, [
    '// Generated by Pynect from @chanx-js/codegen validators. Do not edit.',
    '',
    "import type { z } from 'zod';",
    'import type {',
    ...imports,
    "} from './schemas.zod.js';",
    '',
    ...aliases,
    '',
  ].join('\n'), 'utf8');
}

async function exportSchema(project: PynectProject): Promise<void> {
  const child = await spawnWorker(
    project,
    ['-c', 'from pynect.schema import main; main()'],
    {
      env: {
        PYNECT_APP: project.app,
        PYNECT_SCHEMA_PATH: project.schemaPath,
        PYTHONUNBUFFERED: '1',
      },
      stdio: ['ignore', 'inherit', 'inherit'],
    },
  );
  await waitForChild(child, 'Python schema export');
}
