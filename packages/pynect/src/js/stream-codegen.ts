import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  analyze,
  camelCase,
  type AsyncAPIDocument,
  type OperationObject,
} from '@chanx-js/codegen';

interface StreamOperation extends OperationObject {
  readonly 'x-pynect-stream'?: boolean;
}

interface StreamSpec {
  readonly channel: string;
  readonly functionName: string;
  readonly requestAction: string;
  readonly requestType: string;
  readonly responses: ReadonlyArray<{
    readonly action: string;
    readonly type: string;
  }>;
}

/** Emit operation-specific async iterators for Python iterator handlers. */
export async function emitStreamHelpers(
  document: AsyncAPIDocument,
  outDir: string,
): Promise<string> {
  const streamsPath = path.join(outDir, 'streams.ts');
  await writeFile(streamsPath, renderStreamHelpers(document), 'utf8');

  const indexPath = path.join(outDir, 'index.ts');
  const index = await readFile(indexPath, 'utf8');
  const streamExport = "export * from './streams.js';";
  if (!index.includes(streamExport)) {
    await writeFile(indexPath, `${index.trimEnd()}\n${streamExport}\n`, 'utf8');
  }
  return streamsPath;
}

export function renderStreamHelpers(document: AsyncAPIDocument): string {
  const streams = streamSpecs(document);
  const header = [
    '// Generated by Pynect. Do not edit.',
    '// Regenerate with: pynect generate',
    '',
  ];
  if (streams.length === 0) return `${header.join('\n')}export {};\n`;

  const channels = [...new Set(streams.map(stream => stream.channel))].sort();
  const types = [...new Set(streams.flatMap(stream => [
    stream.requestType,
    ...stream.responses.map(response => response.type),
  ]))].sort();
  const imports = [
    "import { ChanxRequestError, createClient, type ClientOptions } from '@chanx-js/client';",
    `import { ${channels.join(', ')} } from './channels.js';`,
    `import type { ${types.join(', ')} } from './schemas.js';`,
    '',
  ];
  return `${[...header, ...imports, ...streams.flatMap(renderStream)].join('\n').trimEnd()}\n`;
}

function streamSpecs(document: AsyncAPIDocument): StreamSpec[] {
  const connections = analyze(document);
  return Object.entries(document.operations ?? {}).flatMap(([name, rawOperation]) => {
    const operation = rawOperation as StreamOperation;
    if (operation['x-pynect-stream'] !== true) return [];

    const channelKey = referenceName(operation.channel?.$ref, `stream operation ${name} channel`);
    const connection = connections.find(candidate => candidate.key === channelKey);
    if (!connection) throw new Error(`Streaming operation ${name} has no generated channel.`);
    const requestType = messageSchemaName(
      document,
      operation.messages?.[0]?.$ref,
      `stream operation ${name} request`,
    );
    const responses = (operation.reply?.messages ?? []).map((message, index) => {
      const type = messageSchemaName(
        document,
        message.$ref,
        `stream operation ${name} reply ${index + 1}`,
      );
      return { action: messageAction(document, type), type };
    });
    if (responses.length === 0) {
      throw new Error(`Streaming operation ${name} must declare at least one reply message.`);
    }
    return [{
      channel: camelCase(connection.name),
      functionName: camelCase(name),
      requestAction: messageAction(document, requestType),
      requestType,
      responses,
    }];
  });
}

function messageSchemaName(
  document: AsyncAPIDocument,
  messageReference: string | undefined,
  context: string,
): string {
  const messageName = referenceName(messageReference, context);
  const schemaReference = document.components?.messages?.[messageName]?.payload?.$ref;
  return referenceName(schemaReference, `${context} schema`);
}

function messageAction(document: AsyncAPIDocument, schemaName: string): string {
  const action = document.components?.schemas?.[schemaName]?.properties?.action?.const;
  if (typeof action !== 'string') {
    throw new Error(`Streaming message ${schemaName} must have a constant string action.`);
  }
  return action;
}

function referenceName(reference: string | undefined, context: string): string {
  const name = reference?.split('/').at(-1);
  if (!name) throw new Error(`${context} is missing a reference.`);
  return name;
}

function renderStream(stream: StreamSpec): string[] {
  const outputType = stream.responses.map(response => response.type).join(' | ');
  const responseCases = stream.responses.map(response => [
    `        case '${response.action}':`,
    '          yield response;',
    '          break;',
  ]).flat();
  return [
    `export async function* ${stream.functionName}(`,
    '  options: ClientOptions,',
    `  payload: ${stream.requestType}['payload'],`,
    `): AsyncGenerator<${outputType}> {`,
    `  const connection = createClient(options).connect(${stream.channel});`,
    '  const responses = connection.stream();',
    '  let failure: ChanxRequestError | undefined;',
    '  const stopComplete = connection.onComplete(() => { responses.close(); });',
    '  const stopError = connection.onError(frame => {',
    '    failure = new ChanxRequestError(frame);',
    '    responses.close();',
    '  });',
    '  try {',
    '    await connection.ready({ timeout: 5_000 });',
    `    connection.send({ action: '${stream.requestAction}', payload });`,
    '    for await (const response of responses) {',
    '      switch (response.action) {',
    ...responseCases,
    '      }',
    '    }',
    '    if (failure) throw failure;',
    '  } finally {',
    '    stopComplete();',
    '    stopError();',
    '    responses.close();',
    "    connection.terminate(1000, 'Stream complete');",
    '  }',
    '}',
    '',
  ];
}
