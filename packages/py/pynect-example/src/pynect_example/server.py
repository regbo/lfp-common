"""Small HTTP/WebSocket host for the otherwise HTTP-neutral demo service."""

from chanx.fast_channels import asyncapi_docs, asyncapi_spec_json
from chanx.fast_channels.type_defs import AsyncAPIConfig
from fastapi import FastAPI, Request
from fastapi.responses import HTMLResponse, JSONResponse

from pynect_example.chat_service import app as service_app

app = FastAPI(title="Pynect example", version="1.0.0")
app.router.add_websocket_route("/ws/demo", service_app)


asyncapi_conf = AsyncAPIConfig(
    description="Weather, event-stream, and chat examples generated by Chanx",
    version="1.0.0",
)


@app.get("/", response_class=HTMLResponse)
async def home() -> str:
    return """<!doctype html>
<html lang="en">
  <head><meta charset="utf-8"><title>Pynect example</title></head>
  <body>
    <main>
      <h1>Pynect example</h1>
      <p>The same Python service is available over WebSocket at <code>/ws/demo</code> and owned stdio IPC.</p>
      <ul>
        <li><code>get_weather</code> returns one weather snapshot.</li>
        <li><code>watch_weather</code> streams generated weather-change events.</li>
        <li><code>chat</code> keeps a connection-local conversation transcript in Python.</li>
      </ul>
      <p><a href="/asyncapi">AsyncAPI documentation</a> · <a href="/health">Health check</a></p>
    </main>
  </body>
</html>"""


@app.get("/health")
async def health() -> dict[str, str]:
    return {"status": "ok"}


@app.get("/asyncapi")
async def asyncapi_documentation(request: Request) -> HTMLResponse:
    return await asyncapi_docs(request=request, app=app, config=asyncapi_conf)


@app.get("/asyncapi.json")
async def asyncapi_json_spec(request: Request) -> JSONResponse:
    return await asyncapi_spec_json(request=request, app=app, config=asyncapi_conf)
